/*
 * Re-downloads the self-hosted webfonts and regenerates fonts.css.
 *
 *   node tools/fetch-fonts.js
 *
 * Only the `latin` subset of each family is kept — the app is English-only.
 * Inter and Sora are served by Google as variable fonts (one file covering every
 * weight), so the duplicate per-weight downloads are collapsed into a single file.
 *
 * Inter, Sora, and IBM Plex Mono are all SIL Open Font License 1.1.
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.join(__dirname, '..');
const FONT_DIR = path.join(ROOT, 'fonts');
const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Sora:wght@400;600;800' +
  '&family=Inter:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500;600&display=swap';

// A desktop UA is required, or Google serves legacy .ttf instead of .woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

// Families whose single variable file covers a whole weight range.
const VARIABLE = { Inter: '100 900', Sora: '100 800' };

const fetch = (url, binary) =>
  new Promise((resolve, reject) => {
    https
      .get(url, { headers: { 'User-Agent': UA } }, (res) => {
        if (res.statusCode !== 200) {
          return reject(new Error(`${url} -> HTTP ${res.statusCode}`));
        }
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          const buf = Buffer.concat(chunks);
          resolve(binary ? buf : buf.toString('utf8'));
        });
      })
      .on('error', reject);
  });

/** Pull the `latin` @font-face blocks out of the Google Fonts stylesheet. */
function parseLatinFaces(css) {
  const faces = [];
  const parts = css.split('@font-face');
  let preamble = parts[0];
  for (const part of parts.slice(1)) {
    const body = part.slice(0, part.indexOf('}') + 1);
    const subsetComments = preamble.match(/\/\*\s*([a-z-]+)\s*\*\//g) || [];
    const subset = subsetComments[subsetComments.length - 1] || '';
    if (/\/\*\s*latin\s*\*\//.test(subset)) {
      faces.push({
        family: /font-family:\s*'([^']+)'/.exec(body)[1],
        weight: /font-weight:\s*(\d+)/.exec(body)[1],
        url: /url\((https:[^)]+\.woff2)\)/.exec(body)[1],
        range: /unicode-range:\s*([^;]+);/.exec(body)[1].trim(),
      });
    }
    preamble = part.slice(part.indexOf('}') + 1);
  }
  return faces;
}

function slug(family) {
  return family.toLowerCase().replace(/\s+/g, '-');
}

(async () => {
  const css = await fetch(CSS_URL, false);
  const faces = parseLatinFaces(css);
  if (!faces.length) throw new Error('no latin @font-face blocks found');

  fs.mkdirSync(FONT_DIR, { recursive: true });
  // Drop any file we are about to replace, so removed weights do not linger.
  for (const f of fs.readdirSync(FONT_DIR)) {
    if (f.endsWith('.woff2')) fs.unlinkSync(path.join(FONT_DIR, f));
  }

  const rules = [];
  const seen = new Set();

  for (const face of faces) {
    const isVariable = face.family in VARIABLE;
    if (isVariable && seen.has(face.family)) continue; // one file covers all weights
    seen.add(face.family);

    const file = isVariable
      ? `${slug(face.family)}-var.woff2`
      : `${slug(face.family)}-${face.weight}.woff2`;

    const bytes = await fetch(face.url, true);
    fs.writeFileSync(path.join(FONT_DIR, file), bytes);
    console.log(`${face.family} ${isVariable ? '(variable)' : face.weight}`.padEnd(28), file, bytes.length + 'b');

    rules.push(
      `@font-face{font-family:'${face.family}';font-style:normal;` +
        `font-weight:${isVariable ? VARIABLE[face.family] : face.weight};font-display:swap;\n` +
        `  src:url(fonts/${file}) format('woff2');\n` +
        `  unicode-range:${face.range}}`
    );
  }

  const header = `/*
 * Self-hosted latin subsets of the three Google fonts the app uses.
 * Bundled rather than @import-ed from fonts.googleapis.com so the app renders
 * in its real typefaces with no network — an @import would silently fall back
 * to system fonts offline.
 *
 * Inter and Sora are variable fonts: one file each covers every weight.
 * All three are licensed under the SIL Open Font License 1.1.
 *
 * Generated by tools/fetch-fonts.js — do not edit by hand.
 */\n`;

  fs.writeFileSync(path.join(ROOT, 'fonts.css'), header + rules.join('\n') + '\n');
  console.log(`\n${rules.length} faces -> fonts.css`);
  console.log('Remember to bump CACHE_VERSION in sw.js if any file changed.');
})().catch((err) => {
  console.error('FAILED:', err.message);
  process.exit(1);
});
